"""Ports du VS01 : identité attestée par l'hôte, temps, IDs et transaction."""
from __future__ import annotations

from dataclasses import dataclass
from datetime import datetime
from typing import Protocol

from .domain import DomainEvent, Project, ProjectId, Task, TaskId


@dataclass(frozen=True, slots=True)
class ActorContext:
    """Entrée fournie par un hôte de confiance, PAS une preuve d'authentification."""
    subject_id: str
    allowed_scopes: frozenset[str]


class Clock(Protocol):
    def now(self) -> datetime: ...


class IdFactory(Protocol):
    def project_id(self) -> ProjectId: ...
    def task_id(self) -> TaskId: ...


class AuthorizationPolicy(Protocol):
    def require(self, actor: ActorContext, action: str, *, scope: str, owner_id: str) -> None: ...


class UnitOfWork(Protocol):
    def __enter__(self) -> UnitOfWork: ...
    def __exit__(self, exc_type: object, exc: object, tb: object) -> None: ...
    def get_project(self, id: ProjectId) -> Project: ...
    def get_task(self, id: TaskId) -> Task: ...
    def list_tasks(self, project_id: ProjectId) -> tuple[Task, ...]: ...
    def add_project(self, project: Project) -> None: ...
    def save_project(self, project: Project) -> None: ...
    def add_task(self, task: Task) -> None: ...
    def save_task(self, task: Task) -> None: ...
    def record(self, event: DomainEvent) -> None: ...
    def commit(self) -> tuple[DomainEvent, ...]: ...


class UnitOfWorkFactory(Protocol):
    def __call__(self) -> UnitOfWork: ...
